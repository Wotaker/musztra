import { bad, type CatalogEntry, type CommandExample } from './types';

/**
 * Komendy z regulaminu poza zakresem MVP (COMMANDS, „Poza MVP”). Gramatyka je rozpoznaje,
 * a interpreter odpowiada E_OUT_OF_SCOPE z numerem punktu — użytkownik wie, że komenda istnieje.
 */

const OUT_OF_SCOPE_NOTE = 'Komenda istnieje w regulaminie, ale ta wersja symulatora jej nie obsługuje.';

function outOfScope(
  id: string,
  name: string,
  rule: string,
  points: readonly string[],
  quote: string,
  examples: readonly string[],
  docs: Readonly<Record<string, string>> = {},
): CatalogEntry {
  const list: CommandExample[] = examples.map((text) => bad(text, 'E_OUT_OF_SCOPE', docs[text]));
  return {
    id,
    group: 'N',
    name,
    stage: null,
    rule,
    pattern: examples[0] ?? name,
    forms: [],
    executives: [],
    points,
    quote,
    description: OUT_OF_SCOPE_NOTE,
    preconditions: '—',
    effect: '—',
    examples: list,
  };
}

